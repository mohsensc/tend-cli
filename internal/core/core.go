// Package core holds the types every stage of tend speaks.
package core

import (
	"context"
	"strings"
	"time"
)

// Ecosystem names appear in config, state, branch names and output. They never change.
const (
	Npm      = "npm"
	Go       = "go"
	Pip      = "pip"
	Maven    = "maven"
	Gradle   = "gradle"
	Cargo    = "cargo"
	Gems     = "rubygems"
	Composer = "composer"
	Nuget    = "nuget"
	Docker   = "docker"
	Actions  = "actions"

	// What no ecosystem above covers: runtime pins, git refs, Terraform,
	// Helm, and versions named in tend.yml.
	Toolchain = "toolchain"
	Git       = "git"
	Terraform = "terraform"
	Helm      = "helm"
	Custom    = "custom"
)

type Manifest struct {
	Ecosystem string
	Path      string // relative to the repo root: "package.json", "api/go.mod", "Dockerfile"
	Lock      string // relative path of the lockfile, "" if none
	Tool      string // native tool: npm|pnpm|yarn, pip|poetry|uv, mvn|gradle, cargo, bundle, composer, dotnet, docker, actions
}

type Dep struct {
	Ecosystem string
	Name      string // canonical name (see each adapter in the plan)
	Version   string // locked/resolved version; docker tag; actions ref as written. "" if unknown
	Req       string // requirement as written in the manifest
	Manifest  Manifest
	Line      int // 1-based line in Manifest.Path, 0 if unknown
	Dev       bool
	Direct    bool   // false for lockfile-only (transitive) deps
	Pin       string // actions: commit sha when sha-pinned; docker: digest when present
	Min       bool   `json:",omitempty"` // toolchain: the oldest runtime the project supports, not one it runs
}

// Display is the name a person knows d by: node, not the registry's
// library/node.
func (d Dep) Display() string { return strings.TrimPrefix(d.Name, "library/") }

type Release struct {
	Version    string
	Time       time.Time // zero when the registry has no timestamp
	Pre        bool
	Yanked     bool              // yanked, retracted or unlisted: never a target
	Deprecated string            // per-version deprecation message, "" if none
	Peers      map[string]string `json:",omitempty"` // npm: the peer dependencies of this release
}

type Meta struct {
	Name        string
	Releases    []Release // ascending by version
	Latest      string    // the registry's stable "latest", "" if it has no such notion
	Repo        string    // https URL of the source repo, "" if unknown
	Deprecated  string    // whole-package deprecation/abandonment message, "" if none
	Replacement string    // registry-declared replacement package, "" if none
}

// Commands are shell lines run with `sh -c` inside the worktree, in order.
type Commands struct {
	Install []string
	Build   []string
	Test    []string
}

type Bump struct {
	Files  []string // changed paths, relative to root
	Locked bool     // the lockfile was regenerated by the native tool
	Note   string   // why Locked is false, e.g. "pnpm not found"
	// Landed is the release the lockfile took when it is past the one asked
	// for: a tool that moves a dep only the lockfile names takes the newest
	// release its ranges allow, so the release asked for is a floor.
	Landed string
}

// Ecosystem is one self-contained file under internal/eco.
type Ecosystem interface {
	Name() string
	// Detect returns every manifest of this ecosystem under root (git-ignored paths excluded).
	Detect(root string) ([]Manifest, error)
	// Deps reads a manifest and its lockfile. Direct deps come first, in manifest order.
	Deps(root string, m Manifest) ([]Dep, error)
	// Meta fetches registry metadata for a package. Releases ascending, yanked flagged.
	Meta(ctx context.Context, f Fetcher, name string) (*Meta, error)
	// Bump rewrites the requirement in d.Manifest to reach `to` (or swaps the package when
	// toName != "") and regenerates the lockfile with the native tool. root is a worktree.
	// A dep only the lockfile names reaches to or a later release of its
	// major, which Bump.Landed then names.
	Bump(ctx context.Context, root string, d Dep, to, toName string) (*Bump, error)
	// Commands are the default install/build/test lines when tend.yml sets none.
	Commands(root string, m Manifest) Commands
	// Imports lists the names code uses to import d (npm name, module path, python modules, ...).
	Imports(d Dep) []string
	// Traits are the facts about the ecosystem other stages go by.
	Traits() Traits
}

// GroupBumper is an ecosystem that can move several direct deps of one
// manifest to one version in a single lock pass, for packages that only
// resolve together, such as one that pins the other as a peer.
type GroupBumper interface {
	BumpGroup(ctx context.Context, root string, deps []Dep, to string) (*Bump, error)
}

// Remover is an ecosystem that can take dependencies out of a manifest, for
// the first PR, which removes what nothing uses.
type Remover interface {
	// Remove deletes every requirement on deps, all of one manifest, and
	// regenerates the lockfile with the native tool, as Bump does.
	Remove(ctx context.Context, root string, deps []Dep) (*Bump, error)
}

// Settler is an ecosystem some of whose deps are read in full only once
// their registry metadata is in, such as an Action pinned to a bare commit,
// whose version is the tag on that commit.
type Settler interface {
	// Settle is d with what m tells about it filled in, or an error saying
	// why d cannot be followed.
	Settle(d Dep, m *Meta) (Dep, error)
}

// Traits are what stages outside an adapter need to know about its ecosystem.
type Traits struct {
	OSV        string                   // the ecosystem's name in OSV, "" when OSV does not cover it
	Page       func(name string) string // where a person reads about a package, nil for nowhere
	KeepShape  bool                     // a tag keeps its shape across a bump: node:16-alpine moves to another -alpine tag
	KeepSuffix bool                     // a version keeps its qualifier across a bump: guava's -jre moves to another -jre
	Transitive bool                     // the native tool can move a locked transitive dep by itself
	Tooling    bool                     // it pins what the project runs or builds on, not code it calls: runtimes, base images, CI
}

// Baseliner is an ecosystem that can give a project with weak tests a
// baseline to prove changes against: tests it generates, where they go,
// and the line that runs them.
type Baseliner interface {
	// Suite is where a manifest's generated tests go and how they run, nil
	// when the ecosystem cannot run any for it.
	Suite(root string, m Manifest) *Suite
}

// Suite is a place for generated tests in one ecosystem.
type Suite struct {
	Lang    string   // what the tests are written in, for the model: "JavaScript, with node:test and node:assert"
	Smoke   string   // the smoke test's path, "" when the build already loads every module
	Tests   string   // the path of the tests a model writes
	Checks  []string // build or typecheck lines worth adding when they pass on the base
	Modules []string // what a smoke test would load
	// Load is the line that loads one module and exits, Code the smoke test
	// that loads mods, and Run the test line that runs files, "" when the
	// project's own test lines do.
	Load func(mod string) string
	Code func(mods []string) string
	Run  func(files []string) string
}

// Fetcher is what internal/fetch.Client implements. Declared here so core has no deps.
type Fetcher interface {
	Get(ctx context.Context, url string, opts ...FetchOpt) (*Response, error)
	Post(ctx context.Context, url string, body []byte, opts ...FetchOpt) (*Response, error)
}

type FetchOpt func(*FetchOpts)

type FetchOpts struct {
	Header  map[string]string
	TTL     time.Duration // cache lifetime for Get; 0 means the client default
	NoCache bool
	// Idempotent lets a Post be retried on 429 and 5xx. A Get always may be.
	Idempotent bool
	Timeout    time.Duration // how long one request may take, its body read too; 0 means the client's own
}

type Response struct {
	Status int
	Header map[string][]string
	Body   []byte
	Cached bool
}
